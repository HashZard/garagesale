grant select on public.public_sales to anon, authenticated;

create or replace function public.get_upcoming_sales_near(
  search_longitude double precision,
  search_latitude double precision,
  radius_km integer default 25,
  window_end timestamptz default (now() + interval '14 days'),
  category_filters text[] default null
)
returns table (
  id uuid,
  title text,
  description text,
  address text,
  suburb text,
  state text,
  postcode text,
  longitude double precision,
  latitude double precision,
  start_at timestamptz,
  end_at timestamptz,
  photos text[],
  categories text[],
  source text,
  source_url text,
  distance_km double precision
)
language sql
stable
security invoker
set search_path = ''
as $$
  select
    s.id,
    s.title,
    s.description,
    s.address,
    s.suburb,
    s.state,
    s.postcode,
    extensions.st_x(s.location::extensions.geometry),
    extensions.st_y(s.location::extensions.geometry),
    s.start_at,
    s.end_at,
    s.photos,
    s.categories,
    s.source,
    s.source_url,
    extensions.st_distance(
      s.location,
      extensions.st_setsrid(extensions.st_makepoint(search_longitude, search_latitude), 4326)::extensions.geography
    ) / 1000.0 as distance_km
  from public.sales s
  where s.status = 'published'
    and s.end_at > now()
    and s.start_at < window_end
    and extensions.st_dwithin(
      s.location,
      extensions.st_setsrid(extensions.st_makepoint(search_longitude, search_latitude), 4326)::extensions.geography,
      radius_km * 1000.0
    )
    and (category_filters is null or cardinality(category_filters) = 0 or s.categories && category_filters)
  order by s.start_at asc, distance_km asc
$$;

revoke all on function public.get_upcoming_sales_near(double precision, double precision, integer, timestamptz, text[]) from public;
grant execute on function public.get_upcoming_sales_near(double precision, double precision, integer, timestamptz, text[]) to anon, authenticated;

create table public.rate_limits (
  key_hash text not null,
  action text not null,
  window_started_at timestamptz not null,
  request_count integer not null default 1 check (request_count > 0),
  expires_at timestamptz not null,
  primary key (key_hash, action, window_started_at)
);

alter table public.rate_limits enable row level security;
revoke all on public.rate_limits from anon, authenticated;

create or replace function public.consume_rate_limit(
  limit_key_hash text,
  limit_action text,
  max_requests integer,
  window_seconds integer
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_window timestamptz;
  updated_count integer;
begin
  if max_requests <= 0 or window_seconds <= 0 then
    raise exception 'max_requests and window_seconds must be positive';
  end if;

  current_window := to_timestamp(
    floor(extract(epoch from clock_timestamp()) / window_seconds) * window_seconds
  );

  insert into public.rate_limits (
    key_hash,
    action,
    window_started_at,
    request_count,
    expires_at
  ) values (
    limit_key_hash,
    limit_action,
    current_window,
    1,
    current_window + make_interval(secs => window_seconds)
  )
  on conflict (key_hash, action, window_started_at)
  do update set request_count = rate_limits.request_count + 1
  returning request_count into updated_count;

  return updated_count <= max_requests;
end;
$$;

revoke all on function public.consume_rate_limit(text, text, integer, integer) from public;
grant execute on function public.consume_rate_limit(text, text, integer, integer) to service_role;

create or replace function public.delete_expired_rate_limits()
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  deleted_count integer;
begin
  delete from public.rate_limits where expires_at < now();
  get diagnostics deleted_count = row_count;
  return deleted_count;
end;
$$;

revoke all on function public.delete_expired_rate_limits() from public;
grant execute on function public.delete_expired_rate_limits() to service_role;
