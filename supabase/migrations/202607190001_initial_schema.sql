-- GarageSale MVP 初始数据结构：活动、郊区、公开查询和服务端限流。

create schema if not exists extensions;
create extension if not exists postgis schema extensions;

create or replace function public.sale_timezone(sale_state text)
returns text
language sql
immutable
set search_path = ''
as $$
  select case sale_state
    when 'WA' then 'Australia/Perth'
    when 'NSW' then 'Australia/Sydney'
    when 'VIC' then 'Australia/Melbourne'
    when 'QLD' then 'Australia/Brisbane'
    when 'SA' then 'Australia/Adelaide'
    when 'TAS' then 'Australia/Hobart'
    when 'ACT' then 'Australia/Sydney'
    when 'NT' then 'Australia/Darwin'
    else 'Australia/Sydney'
  end
$$;

create table public.suburbs (
  id bigint generated by default as identity primary key,
  name text not null,
  state text not null check (state in ('WA', 'NSW', 'VIC', 'QLD', 'SA', 'TAS', 'ACT', 'NT')),
  postcode text not null check (postcode ~ '^[0-9]{4}$'),
  slug text not null unique,
  location extensions.geography(Point, 4326) not null,
  created_at timestamptz not null default now(),
  unique (name, state, postcode)
);

create index suburbs_location_gist_idx on public.suburbs using gist (location);
create index suburbs_name_search_idx on public.suburbs (lower(name) text_pattern_ops);
create index suburbs_postcode_idx on public.suburbs (postcode);

create table public.sales (
  id uuid primary key default gen_random_uuid(),
  title text not null check (char_length(trim(title)) between 1 and 80),
  description text check (description is null or char_length(description) <= 2000),
  address text not null check (char_length(trim(address)) > 0),
  suburb text not null check (char_length(trim(suburb)) > 0),
  state text not null check (state in ('WA', 'NSW', 'VIC', 'QLD', 'SA', 'TAS', 'ACT', 'NT')),
  postcode text not null check (postcode ~ '^[0-9]{4}$'),
  location extensions.geography(Point, 4326) not null,
  start_at timestamptz not null,
  end_at timestamptz not null,
  photos text[] not null default '{}',
  categories text[] not null default '{}',
  source text not null default 'self' check (source in ('self', 'gumtree', 'facebook', 'manual', 'other')),
  source_url text,
  contact_email text,
  manage_token uuid unique,
  status text not null default 'pending_verification' check (status in ('pending_verification', 'published', 'cancelled', 'removed')),
  email_verified_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint sales_time_order_check check (end_at > start_at),
  constraint sales_single_local_day_check check (
    (start_at at time zone public.sale_timezone(state))::date =
    (end_at at time zone public.sale_timezone(state))::date
  ),
  constraint sales_photo_count_check check (cardinality(photos) <= 6),
  constraint sales_photo_values_check check (array_position(photos, null) is null),
  constraint sales_categories_check check (
    categories <@ array[
      'furniture', 'tools', 'clothing', 'kids-baby', 'books-media',
      'electronics', 'garden', 'collectables', 'household', 'other'
    ]::text[]
  ),
  constraint sales_self_fields_check check (
    (
      source = 'self'
      and contact_email is not null
      and manage_token is not null
      and source_url is null
    )
    or
    (
      source <> 'self'
      and contact_email is null
      and manage_token is null
      and source_url is not null
    )
  ),
  constraint sales_verification_check check (
    (status = 'pending_verification' and email_verified_at is null)
    or status <> 'pending_verification'
  )
);

create index sales_location_gist_idx on public.sales using gist (location);
create index sales_state_suburb_idx on public.sales (state, suburb);
create index sales_start_at_idx on public.sales (start_at);
create index sales_status_end_at_idx on public.sales (status, end_at);
create index sales_contact_email_idx on public.sales (lower(contact_email)) where contact_email is not null;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger sales_set_updated_at
before update on public.sales
for each row execute function public.set_updated_at();

