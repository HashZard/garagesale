create or replace view public.public_sales
with (security_invoker = true, security_barrier = true)
as
select
  id,
  title,
  description,
  address,
  suburb,
  state,
  postcode,
  extensions.st_x(location::extensions.geometry) as longitude,
  extensions.st_y(location::extensions.geometry) as latitude,
  start_at,
  end_at,
  photos,
  categories,
  source,
  source_url,
  created_at,
  updated_at
from public.sales
where status = 'published' and end_at > now();

